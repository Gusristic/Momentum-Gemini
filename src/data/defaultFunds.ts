// Helper to generate consistent monthly historical points for 60 months (2021-09 to 2026-09)
function generateHistory(
  finalNav: number,
  monthlyReturns: number[],
  benchmarkReturns: number[],
  rfRateMonthly: number = 0.0028 // ~3.4% annual €STR
): HistoricalDataPoint[] {
  const points: HistoricalDataPoint[] = [];
  const now = new Date();
  const totalPoints = monthlyReturns.length;
  
  // Backward computation ensures points[totalPoints - 1].nav === finalNav exactly
  const navs: number[] = new Array(totalPoints);
  navs[totalPoints - 1] = finalNav;
  for (let i = totalPoints - 2; i >= 0; i--) {
    const nextR = monthlyReturns[i + 1] ?? 0.008;
    navs[i] = Number((navs[i + 1] / (1 + nextR)).toFixed(4));
  }

  const benchs: number[] = new Array(totalPoints);
  benchs[totalPoints - 1] = 100;
  for (let i = totalPoints - 2; i >= 0; i--) {
    const nextB = benchmarkReturns[i + 1] ?? 0.008;
    benchs[i] = Number((benchs[i + 1] / (1 + nextB)).toFixed(4));
  }

  const rfs: number[] = new Array(totalPoints);
  rfs[totalPoints - 1] = 100;
  for (let i = totalPoints - 2; i >= 0; i--) {
    rfs[i] = Number((rfs[i + 1] / (1 + rfRateMonthly)).toFixed(4));
  }

  for (let i = 0; i < totalPoints; i++) {
    const d = new Date(now.getFullYear(), now.getMonth() - (totalPoints - 1 - i), 1);
    const dateStr = d.toISOString().split('T')[0].substring(0, 7); // YYYY-MM
    points.push({
      date: dateStr,
      nav: Number(navs[i].toFixed(2)),
      benchmarkNav: Number(benchs[i].toFixed(2)),
      riskFreeNav: Number(rfs[i].toFixed(2)),
    });
  }
  
  return points;
}

